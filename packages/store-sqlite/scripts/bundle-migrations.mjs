#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const journal = JSON.parse(readFileSync(join(root, 'drizzle/meta/_journal.json'), 'utf8'))

const entries = journal.entries.map((entry) => {
  const body = readFileSync(join(root, 'drizzle', `${entry.tag}.sql`), 'utf8')
  return {
    tag: entry.tag,
    when: entry.when,
    breakpoints: entry.breakpoints,
    hash: createHash('sha256').update(body).digest('hex'),
    body,
  }
})

const out = `// Generated by scripts/bundle-migrations.mjs. Do not edit.
export const bundledMigrations = ${JSON.stringify(entries, null, 2)} as const
`

writeFileSync(join(root, 'src/migrations.bundle.ts'), out)
console.log(`bundled ${entries.length} migrations`)
